using Commonage.Web.Domain;
using Microsoft.AspNetCore.DataProtection.EntityFrameworkCore;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using NpgsqlTypes;

namespace Commonage.Web.Data;

public class CommonageDbContext(DbContextOptions<CommonageDbContext> options)
    : IdentityDbContext<IdentityUser>(options), IDataProtectionKeyContext
{
    public DbSet<Collection> Collections => Set<Collection>();
    public DbSet<ArchiveItem> ArchiveItems => Set<ArchiveItem>();
    public DbSet<MediaFile> MediaFiles => Set<MediaFile>();
    public DbSet<Tag> Tags => Set<Tag>();
    public DbSet<ContributionLink> ContributionLinks => Set<ContributionLink>();
    public DbSet<Contribution> Contributions => Set<Contribution>();
    public DbSet<VisitorNote> VisitorNotes => Set<VisitorNote>();
    public DbSet<AuditEntry> AuditEntries => Set<AuditEntry>();
    public DbSet<ArchiveSettings> ArchiveSettings => Set<ArchiveSettings>();
    public DbSet<ArchiveText> ArchiveTexts => Set<ArchiveText>();

    // Keys that encrypt login cookies. Stored in the database so logins survive container rebuilds.
    public DbSet<DataProtectionKey> DataProtectionKeys => Set<DataProtectionKey>();

    /// <summary>
    /// Full-text index of an item, generated by PostgreSQL from its title, tags, date and description.
    /// A shadow property: query it with <c>EF.Property&lt;NpgsqlTsVector&gt;(item, SearchVector)</c>.
    /// </summary>
    public const string SearchVector = "SearchVector";

    /// <summary>
    /// The text search configuration: lower-cases words but does not stem them, so German and English text are
    /// treated alike. <see cref="Search.ItemSearch"/> matches word beginnings to make up for it.
    /// </summary>
    public const string SearchConfiguration = "simple";

    /// <summary>
    /// The database function that removes accents before text is indexed or searched, so "Muhle" finds "Mühle".
    /// See <see cref="AccentFolding"/>.
    /// </summary>
    public const string FoldFunction = "commonage_fold";

    /// <summary>Items the public may see. Every public page must start from this query.</summary>
    public IQueryable<ArchiveItem> PublishedItems => ArchiveItems.Where(i => i.Status == ItemStatus.Published);

    /// <summary>Items in the bin. Query filters hide them from every other query, see <see cref="OnModelCreating"/>.</summary>
    public IQueryable<ArchiveItem> BinnedItems => ArchiveItems.IgnoreQueryFilters().Where(i => i.DeletedAt != null);

    /// <summary>Photos in the bin on their own. The photos of an item in the bin go and come back with the item.</summary>
    public IQueryable<MediaFile> BinnedPhotos =>
        MediaFiles.IgnoreQueryFilters().Where(f => f.DeletedAt != null && f.ArchiveItem.DeletedAt == null);

    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);

        builder.Entity<Collection>(collection =>
        {
            collection.Property(c => c.Title).HasMaxLength(200);
            collection.Property(c => c.Description).HasMaxLength(4000);
            collection.HasIndex(c => c.Position);
            // A photo deleted for good leaves the collection without a chosen cover, not without its page.
            collection.HasOne<MediaFile>()
                .WithMany()
                .HasForeignKey(c => c.CoverMediaFileId)
                .OnDelete(DeleteBehavior.SetNull);
        });

        builder.Entity<ArchiveItem>(item =>
        {
            item.HasQueryFilter(i => i.DeletedAt == null);
            item.Property(i => i.Version).IsRowVersion();
            item.Property(i => i.Title).HasMaxLength(300);
            item.Property(i => i.Description).HasMaxLength(20000);
            item.Property(i => i.DateText).HasMaxLength(DateRange.MaxTextLength);
            item.Property(i => i.RightsUri).HasMaxLength(RightsOptions.MaxUriLength);
            item.Property(i => i.RightsHolder).HasMaxLength(300);
            item.Property(i => i.Credit).HasMaxLength(300);
            item.Property(i => i.ReferenceNumber).HasMaxLength(100);
            item.Property(i => i.OriginalLocation).HasMaxLength(300);
            item.Property(i => i.ReceivedFrom).HasMaxLength(300);
            item.Property(i => i.ReceivedOn).HasMaxLength(100);
            item.Property(i => i.InternalNotes).HasMaxLength(20000);
            item.HasIndex(i => i.ReferenceNumber).IsUnique();
            item.HasIndex(i => i.Status);
            item.HasIndex(i => i.DateFrom);
            item.HasIndex(i => i.DateTo);
            item.HasMany(i => i.Tags).WithMany(t => t.Items);
            // Kept on one line: line breaks would differ between Windows and Linux checkouts and look like a model change.
            item.Property<NpgsqlTsVector>(SearchVector).HasComputedColumnSql(
                $"""setweight(to_tsvector('{SearchConfiguration}', {FoldFunction}(coalesce("Title", ''))), 'A') || """ +
                $"""setweight(to_tsvector('{SearchConfiguration}', {FoldFunction}(coalesce("TagNames", '') || ' ' || coalesce("DateText", ''))), 'B') || """ +
                $"""setweight(to_tsvector('{SearchConfiguration}', {FoldFunction}(coalesce("Description", ''))), 'C')""",
                stored: true);
            item.HasIndex(SearchVector).HasMethod("GIN");
            item.HasOne(i => i.Collection)
                .WithMany(c => c.Items)
                .OnDelete(DeleteBehavior.Restrict);
        });

        builder.Entity<Tag>(tag =>
        {
            tag.Property(t => t.Name).HasMaxLength(Tag.MaxLength);
            tag.Property(t => t.NormalizedName).HasMaxLength(Tag.MaxLength);
            tag.HasIndex(t => t.NormalizedName).IsUnique();
        });

        builder.Entity<ContributionLink>(link =>
        {
            link.Property(l => l.Title).HasMaxLength(ContributionLink.TitleMaxLength);
            link.Property(l => l.Introduction).HasMaxLength(ContributionLink.IntroductionMaxLength);
            link.Property(l => l.Token).HasMaxLength(32);
            link.HasIndex(l => l.Token).IsUnique();
            link.HasOne(l => l.Collection)
                .WithMany()
                .OnDelete(DeleteBehavior.Restrict);
        });

        builder.Entity<VisitorNote>(note =>
        {
            // Goes and comes back with its item, like the item's contribution.
            note.HasQueryFilter(n => n.ArchiveItem.DeletedAt == null);
            note.Property(n => n.Message).HasMaxLength(VisitorNote.MessageMaxLength);
            note.Property(n => n.Name).HasMaxLength(Contribution.NameMaxLength);
            note.Property(n => n.Email).HasMaxLength(Contribution.EmailMaxLength);
            note.HasIndex(n => n.HandledAt);
            note.HasOne(n => n.ArchiveItem)
                .WithMany()
                .OnDelete(DeleteBehavior.Cascade);
        });

        builder.Entity<Contribution>(contribution =>
        {
            contribution.HasQueryFilter(c => c.ArchiveItem.DeletedAt == null);
            contribution.Property(c => c.ContributorName).HasMaxLength(Contribution.NameMaxLength);
            contribution.Property(c => c.ContributorEmail).HasMaxLength(Contribution.EmailMaxLength);
            contribution.Property(c => c.RightsHolder).HasMaxLength(Contribution.RightsHolderMaxLength);
            contribution.Property(c => c.ConsentText).HasMaxLength(4000);
            contribution.Property(c => c.ReferenceCode).HasMaxLength(Contribution.ReferenceCodeLength);
            contribution.HasIndex(c => c.ReferenceCode).IsUnique();
            contribution.Property(c => c.SendingFingerprint).HasMaxLength(Contribution.SendingFingerprintLength);
            contribution.HasIndex(c => c.SendingFingerprint).IsUnique();
            contribution.HasIndex(c => c.ArchiveItemId).IsUnique();
            contribution.HasOne(c => c.ArchiveItem)
                .WithOne(i => i.Contribution)
                .HasForeignKey<Contribution>(c => c.ArchiveItemId)
                .OnDelete(DeleteBehavior.Cascade);
            contribution.HasOne(c => c.ContributionLink)
                .WithMany(l => l.Contributions)
                .OnDelete(DeleteBehavior.SetNull);
        });

        builder.Entity<ArchiveSettings>(settings =>
        {
            settings.Property(s => s.Id).ValueGeneratedNever();
            settings.Property(s => s.DefaultLanguage).HasMaxLength(20);
            settings.Property(s => s.ContentLanguage).HasMaxLength(20);
            settings.Property(s => s.OtherContentLanguages).HasMaxLength(200);
            settings.Property(s => s.AccentColor).HasMaxLength(7);
            settings.Property(s => s.TimeZone).HasMaxLength(100);
            settings.Property(s => s.DefaultRightsUri).HasMaxLength(RightsOptions.MaxUriLength);
        });

        builder.Entity<ArchiveText>(text =>
        {
            text.HasKey(t => new { t.Language, t.Kind });
            text.Property(t => t.Language).HasMaxLength(20);
            text.Property(t => t.Kind).HasConversion<string>().HasMaxLength(30);
            text.Property(t => t.Text).HasMaxLength(ArchiveText.MaxLength);
        });

        builder.Entity<AuditEntry>(entry =>
        {
            entry.Property(e => e.UserId).HasMaxLength(450);
            entry.Property(e => e.UserName).HasMaxLength(256);
            entry.Property(e => e.Action).HasConversion<string>().HasMaxLength(50);
            entry.Property(e => e.Subject).HasMaxLength(AuditEntry.SubjectMaxLength);
            entry.HasIndex(e => e.At);
            entry.HasOne(e => e.ArchiveItem)
                .WithMany()
                .OnDelete(DeleteBehavior.SetNull);
        });

        builder.Entity<MediaFile>(file =>
        {
            file.HasQueryFilter(f => f.DeletedAt == null && f.ArchiveItem.DeletedAt == null);
            file.Property(f => f.OriginalFileName).HasMaxLength(255);
            file.Property(f => f.ContentType).HasMaxLength(100);
            file.Property(f => f.Sha256).HasMaxLength(64).IsFixedLength();
            file.Property(f => f.ProcessingError).HasMaxLength(1000);
            file.Property(f => f.AltText).HasMaxLength(1000);
            file.HasIndex(f => f.StorageId).IsUnique();
            file.HasIndex(f => f.Status);
            file.HasIndex(f => f.Sha256);
            file.HasOne(f => f.ArchiveItem)
                .WithMany(i => i.MediaFiles)
                .OnDelete(DeleteBehavior.Cascade);
        });
    }
}
